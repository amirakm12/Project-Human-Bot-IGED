void AIGEDAIController::TrainNeuralNetwork(const TArray<float>& InputData, const TArray<float>& ExpectedOutput)
{
    if (InputData.Num() != ExpectedOutput.Num()) return;
    
    // Simple neural network training simulation
    for (int32 i = 0; i < InputData.Num(); i++)
    {
        float Error = ExpectedOutput[i] - PredictOutput({InputData[i]})[0];
        BackPropagate({Error});
    }
    
    UE_LOG(LogIGED, Warning, TEXT("Neural network trained with %d samples"), InputData.Num());
}

TArray<float> AIGEDAIController::PredictOutput(const TArray<float>& InputData)
{
    TArray<float> Output;
    
    for (float Input : InputData)
    {
        float Result = ActivationFunction(Input * 0.5f + 0.1f);
        Output.Add(Result);
    }
    
    return Output;
}

