void AIGEDAIController::ProcessTaskQueue()
{
    if (TaskQueue.Num() == 0) return;
    
    FAIAgentTask CurrentTask = TaskQueue[0];
    TaskQueue.RemoveAt(0);
    
    ExecuteTask(CurrentTask);
}

void AIGEDAIController::ExecuteCodeGenTask(const FAIAgentTask& Task)
{
    FString Code = GenerateCode(TEXT("C++"), Task.Parameters);
    AgentMemory.Add(Task.TaskID, Code);
}

